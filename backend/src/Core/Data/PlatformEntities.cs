namespace Saaskit.Core.Data;

/// <summary>The first response to a POST with an <c>Idempotency-Key</c>, kept so a retry gets the same answer instead of a duplicate.</summary>
public sealed class IdempotencyRecord
{
    public const int MaxKeyLength = 200;

    public string PrincipalId { get; private set; } = "";

    public string Key { get; private set; } = "";

    /// <summary>A hash of the request body: the same key with a different body is a mistake, not a retry.</summary>
    public string RequestHash { get; private set; } = "";

    public DateTime CreatedOn { get; private set; }

    public int? StatusCode { get; private set; }

    public string? ContentType { get; private set; }

    public string? ResponseBody { get; private set; }

    public string? Location { get; private set; }

    public bool IsCompleted => StatusCode is not null;

    public static IdempotencyRecord Start(string principalId, string key, string requestHash, DateTime utcNow) =>
        new() { PrincipalId = principalId, Key = key, RequestHash = requestHash, CreatedOn = utcNow };

    public void Complete(int statusCode, string? contentType, string? responseBody, string? location)
    {
        StatusCode = statusCode;
        ContentType = contentType;
        ResponseBody = responseBody;
        Location = location;
    }
}

public enum StoredFileStatus
{
    /// <summary>Uploaded, not yet scanned. Not downloadable.</summary>
    Quarantined = 0,
    Clean = 1,
    Rejected = 2,
}

/// <summary>Metadata of a file in object storage. The object key and name are generated by the server, never taken from user input.</summary>
public sealed class StoredFile : BaseEntity
{
    public const int MaxKeyLength = 400;

    private StoredFile()
    {
    }

    public StoredFile(string key, string contentType, long length, string sha256, string displayName)
    {
        Key = key;
        ContentType = contentType;
        Length = length;
        Sha256 = sha256;
        DisplayName = displayName;
        Status = StoredFileStatus.Quarantined;
    }

    public string Key { get; private set; } = "";

    public string ContentType { get; private set; } = "";

    public long Length { get; private set; }

    public string Sha256 { get; private set; } = "";

    /// <summary>A sanitised name for showing to people. Not used for storage.</summary>
    public string DisplayName { get; private set; } = "";

    public StoredFileStatus Status { get; private set; }

    public void MarkClean() => Status = StoredFileStatus.Clean;

    public void Reject() => Status = StoredFileStatus.Rejected;
}

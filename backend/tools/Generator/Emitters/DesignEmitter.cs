using System.Globalization;
using System.Text;
using System.Text.Json;

namespace Saaskit.Generator.Emitters;

/// <summary>
/// From the design tokens (frontend/packages/ui-kit/src/theme/tokens.ts, the single source for every visual decision):
/// <c>Core/Generated/DesignTokens.g.cs</c>, which server-rendered pages (Identity's sign-in) use so they never keep their own colours,
/// and <c>docs/design-system.md</c>, the readable reference. The frontend theme reads tokens.ts directly.
/// </summary>
internal static class DesignEmitter
{
    private const string Source = "frontend/packages/ui-kit/src/theme/tokens.ts";
    private const string Notice = $"<auto-generated> Edit {Source} instead and run scripts/generate.";

    public static void Emit(PlatformDefinition platform, GeneratedFiles files)
    {
        var json = Processes.Capture("node", Path.Combine(files.RepoRoot, "frontend"),
            "Node 24 or later is needed to read the design tokens (it runs TypeScript directly).", "scripts/design-tokens.mjs");
        using var document = JsonDocument.Parse(json);
        var leaves = Flatten(document.RootElement, []).ToList();

        EmitCSharp(platform, files, leaves);
        EmitDocs(files, leaves);
    }

    private static void EmitCSharp(PlatformDefinition platform, GeneratedFiles files, List<Leaf> leaves)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"// {Notice}");
        sb.AppendLine("#nullable enable");
        sb.AppendLine($"namespace {platform.ProductPascal}.Core.Platform;");
        sb.AppendLine();
        sb.AppendLine($"/// <summary>The design tokens from {Source}. Server-rendered pages use these, never their own values.</summary>");
        sb.AppendLine("public static class DesignTokens");
        sb.AppendLine("{");
        foreach (var leaf in leaves)
        {
            switch (leaf.Value.ValueKind)
            {
                case JsonValueKind.String:
                    sb.AppendLine($"    public const string {leaf.Identifier} = {Naming.Quote(leaf.Value.GetString()!)};");
                    break;
                case JsonValueKind.Number when leaf.Value.TryGetInt32(out var whole):
                    sb.AppendLine($"    public const int {leaf.Identifier} = {whole.ToString(CultureInfo.InvariantCulture)};");
                    break;
                case JsonValueKind.Number:
                    sb.AppendLine($"    public const double {leaf.Identifier} = {leaf.Value.GetDouble().ToString("0.###", CultureInfo.InvariantCulture)};");
                    break;
            }
        }
        sb.AppendLine("}");
        files.AddRaw("backend/src/Core/Generated/DesignTokens.g.cs", sb.ToString());
    }

    private static void EmitDocs(GeneratedFiles files, List<Leaf> leaves)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"<!-- {Notice} -->");
        sb.AppendLine("# Design system");
        sb.AppendLine();
        sb.AppendLine($"Every visual decision lives in one file: [`{Source}`](../{Source}). It is plain data. The MUI theme reads it directly, and");
        sb.AppendLine("`scripts/generate` derives everything else from it (this page, and `DesignTokens.g.cs` for Identity's server-rendered sign-in pages).");
        sb.AppendLine("A lint rule fails the build on a colour literal anywhere else, and `scripts/generate --check` fails if a derived file is out of date.");
        sb.AppendLine();
        sb.AppendLine("## Rules");
        sb.AppendLine();
        sb.AppendLine("- Use the theme (`theme.palette`, `sx` colour names, `theme.spacing`), never a value. Components in modules and the shell contain no colour, font size or radius literals.");
        sb.AppendLine("- Status is never colour alone: a `StatusChip` always carries text.");
        sb.AppendLine("- Body text and control edges meet WCAG 2.2 AA: 4.5:1 for text, 3:1 for the edge of an input or other control.");
        sb.AppendLine("- A tenant may change the primary colour and logo only. Nothing else about the design varies per tenant.");
        sb.AppendLine("- Two elevations (raised, overlay), two densities (compact, comfortable), one font family.");
        sb.AppendLine();
        foreach (var group in leaves.GroupBy(l => l.Path[0]))
        {
            sb.AppendLine($"## {char.ToUpperInvariant(group.Key[0])}{group.Key[1..]}");
            sb.AppendLine();
            sb.AppendLine("| Token | Value |");
            sb.AppendLine("|---|---|");
            foreach (var leaf in group)
            {
                var text = leaf.Value.ValueKind == JsonValueKind.String ? leaf.Value.GetString()! : leaf.Value.GetRawText();
                sb.AppendLine($"| `{string.Join('.', leaf.Path)}` | `{text.Replace("|", "\\|", StringComparison.Ordinal)}` |");
            }
            sb.AppendLine();
        }
        files.AddRaw("docs/design-system.md", sb.ToString());
    }

    private static IEnumerable<Leaf> Flatten(JsonElement element, string[] path)
    {
        if (element.ValueKind == JsonValueKind.Object)
        {
            foreach (var property in element.EnumerateObject())
            {
                foreach (var leaf in Flatten(property.Value, [.. path, property.Name]))
                    yield return leaf;
            }
        }
        else
        {
            yield return new Leaf(path, element.Clone());
        }
    }

    private sealed record Leaf(string[] Path, JsonElement Value)
    {
        /// <summary><c>color.text.secondaryLight</c> becomes <c>ColorTextSecondaryLight</c>.</summary>
        public string Identifier => string.Concat(Path.Select(p => char.ToUpperInvariant(p[0]) + p[1..]));
    }
}

using System.Diagnostics;
using System.Text;
using System.Text.RegularExpressions;

namespace Saaskit.Generator.Emitters;

/// <summary>
/// deploy/docker-compose.yml is produced from the AppHost with <c>aspire publish</c> (Aspire's Docker Compose publisher),
/// so the AppHost, itself generated from platform.yaml, is its only source. deploy/compose.env.example lists the
/// variables the compose file needs, with no values.
/// </summary>
internal static partial class ComposeEmitter
{
    private const string Notice = "<auto-generated> Produced from the AppHost by `aspire publish`. Edit platform.yaml or the AppHost and run scripts/generate.";

    public static void Emit(GeneratedFiles files)
    {
        var output = Path.Combine(Path.GetTempPath(), $"compose-{Guid.NewGuid():N}");
        try
        {
            Run(Aspire(), files.RepoRoot, "publish", "--project", "backend/src/AppHost/AppHost.csproj", "-o", output, "--non-interactive");
            var compose = File.ReadAllText(Path.Combine(output, "docker-compose.yaml"));
            files.AddRaw("deploy/docker-compose.yml", $"# {Notice}\n{compose}");

            var variables = Variable().Matches(compose).Select(m => m.Groups[1].Value).Distinct().Order(StringComparer.Ordinal);
            var env = new StringBuilder();
            env.AppendLine($"# {Notice}");
            env.AppendLine("# Variables deploy/docker-compose.yml needs. Copy to deploy/.env (git-ignored) and fill in; never commit values.");
            foreach (var variable in variables)
                env.AppendLine($"{variable}=");
            files.AddRaw("deploy/compose.env.example", env.ToString());
        }
        finally
        {
            if (Directory.Exists(output))
                Directory.Delete(output, recursive: true);
        }
    }

    private static string Aspire()
    {
        var fromEnvironment = Environment.GetEnvironmentVariable("ASPIRE_CLI");
        if (!string.IsNullOrEmpty(fromEnvironment))
            return fromEnvironment;
        var home = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".aspire", "bin", OperatingSystem.IsWindows() ? "aspire.exe" : "aspire");
        return File.Exists(home) ? home : "aspire";
    }

    private static void Run(string fileName, string workingDirectory, params string[] arguments)
    {
        var start = new ProcessStartInfo(fileName) { WorkingDirectory = workingDirectory, RedirectStandardOutput = true, RedirectStandardError = true };
        foreach (var argument in arguments)
            start.ArgumentList.Add(argument);
        start.Environment["NO_COLOR"] = "1";
        Process process;
        try
        {
            process = Process.Start(start)!;
        }
        catch (System.ComponentModel.Win32Exception)
        {
            throw new PlatformDefinitionException("The Aspire CLI is required to produce deploy/docker-compose.yml. Install it (https://aspire.dev) or set ASPIRE_CLI.");
        }
        using (process)
        {
            var stdout = process.StandardOutput.ReadToEndAsync();
            var stderr = process.StandardError.ReadToEndAsync();
            process.WaitForExit();
            if (process.ExitCode != 0)
                throw new PlatformDefinitionException($"aspire publish failed ({process.ExitCode}):\n{stdout.Result}\n{stderr.Result}");
        }
    }

    [GeneratedRegex(@"\$\{([A-Z0-9_]+)\}")]
    private static partial Regex Variable();
}
